#!/usr/bin/env bash
# Wait for the P2 and P3 queue jobs; when one experiment's jobs are all DONE (or one FAILED / BLOCKED), paste its
# runs/<exp>/summary/SUMMARY.md into docs/P2_TWO_TOPICS.md / docs/P3_DATA_EFFICIENCY.md (P3 also copies the curves),
# set the status line, commit (author only, no AI trailer) and push prep/later-runs. Never re-runs or re-queues anything.
#   tmux new -d -s p23-watch 'scripts/p23_when_done.sh >> $DSG_RESULTS/p23_watch.log 2>&1'   (restart after a reboot)
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-300}
declare -A DOC=([P2]=docs/P2_TWO_TOPICS.md [P3]=docs/P3_DATA_EFFICIENCY.md)
declare -A DONE_=()
while [ "${#DONE_[@]}" -lt 2 ]; do
  for E in P2 P3; do
    [ -n "${DONE_[$E]:-}" ] && continue
    st=$($PY - "$E" <<'PYEOF'
import json, os, glob, sys
S = os.environ["DSG_RESULTS"] + "/queue/state"
fs = [f for f in glob.glob(f"{S}/{sys.argv[1]}-*.json") if "smoke" not in f]
st = [json.load(open(f)).get("status") for f in fs]
print("BAD" if any(s in ("FAILED", "BLOCKED") for s in st) else
      "DONE" if st and all(s == "DONE" for s in st) else f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
PYEOF
)
    echo "$(date -Iseconds) $E $st"
    case "$st" in BAD|DONE) ;; *) continue ;; esac
    $PY - "$E" "$st" "${DOC[$E]}" <<'PYEOF'
import os, re, shutil, sys
from pathlib import Path
e, st, doc = sys.argv[1:4]
doc = Path(doc)
s = doc.read_text()
run = Path(os.environ["DSG_RESULTS"]) / "runs" / e / "summary"
summ = run / "SUMMARY.md"
if st == "DONE" and summ.exists():
    body = summ.read_text()
    stopped = "**STOP" in body
    status = (f"**{e} status: STOPPED by its rule** (every job finished; see the check below)." if stopped else
              f"**{e} status: DONE** (every {e} job finished; tables generated by `{e}-summary`; verdict at the end).")
    if (run / "P3_curves.png").exists():
        shutil.copy(run / "P3_curves.png", doc.parent / "P3_curves.png")
else:
    body = f"A {e} job FAILED or is BLOCKED (possibly a STOP check): run `python -m dsgx.queue.doctor` and read the job log. No result tables.\n"
    status = f"**{e} status: STOPPED** (a {e} queue job failed or is blocked; see below)."
s = re.sub(rf"<!-- {e}-SUMMARY -->.*<!-- /{e}-SUMMARY -->", lambda m: f"<!-- {e}-SUMMARY -->\n" + body + f"<!-- /{e}-SUMMARY -->", s, flags=re.S)
s = re.sub(rf"^\*\*{e} status:.*$", status, s, count=1, flags=re.M)
doc.write_text(s)
PYEOF
    git add "${DOC[$E]}"; [ -f docs/P3_curves.png ] && git add docs/P3_curves.png
    git commit -q -m "$E (DEV only): ${DOC[$E]} from $E-summary ($st)" && git push -q origin prep/later-runs \
      && echo "$(date -Iseconds) $E committed and pushed ($st)"
    DONE_[$E]=1
  done
  [ "${#DONE_[@]}" -lt 2 ] && sleep "$EVERY"
done
