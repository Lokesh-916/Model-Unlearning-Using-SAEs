"""Generate configs/experiments/E4b.yaml (Step B; DEV only, never TEST).

Runs (WMDP-Bio dev @forget, bs 1) x Step B attacks: base, DSG (rho + clamp, A1-dev selection), StreamGuard v1
(CUSUM + clamp, 5 % MMLU-dev calibration), sgF (StreamGuard v1's clamp forced on every prompt), R6 forced on
(E2e delta). Tasks: scores (GPU, per-prompt L08 / reference scores), stepB (CPU summary). Step A runs offline
(python -m experiments.E4b.stepa), not in the queue.

    python scripts/make_e4b_config.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.E4b.common import STEP_B_ATTACKS  # noqa: E402

DSG = {"name": "dsg-faithful", "select": {"exp_id": "A1-dev", "keys": ["n_features", "retain_pct", "multiplier"],
                                          "max_utility_drop": 0.01}}
SG1 = {"name": "gated", "gate": {"type": "cusum", "n_features": 20, "retain_pct": 95},
       "calib": {"fpr": 0.05, "n_max": 1000, "source": "mmlu-dev"}, "intervention": {"type": "clamp_all", "multiplier": 500}}
SGF = {"name": "gated", "gate": {"type": "cusum", "n_features": 20, "retain_pct": 95, "threshold": -1.0e30},
       "intervention": {"type": "clamp_all", "multiplier": 500}, "forced_on": True}
R6 = {"name": "delta-response", "module": "experiments.E2d.response", "response": "R6", "response_exp": "E2e",
      "forced_on": True}
CONDS = [("base", {"name": "base"}), ("dsg", DSG), ("sg1", SG1), ("sgF", SGF), ("R6", R6)]
HEADER = ("# generated by scripts/make_e4b_config.py; do not edit by hand. DEV split only, never TEST.\n"
          "# E4b Step B: attacks a benign-biology-quiet L08 gate could open (lab PC; exploratory, not a claim input;\n"
          "# DEVIATIONS 2026-11-12 E4b row).\n")


def runs():
    return [{"method": m, "attack": spec, "datasets": ["@forget"], "dataset_label": f"{c}-{a}",
             "e2d": {"cond": c, "attack": a}} for c, m in CONDS for a, spec in STEP_B_ATTACKS.items()]


def main():
    cfg = {
        "exp_id": "E4b", "priority": "must", "wave": 9,
        "base": {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0},
        "runs": runs(),
        "tasks": [
            {"id": "scores", "entry": "experiments.E4b.scores:task", "args": {"fit_exp": "E4a"},
             "smoke_args": {"limit": 6}, "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": 25,
             "smoke_est_minutes": 3, "est_vram_gb": 9, "est_ram_gb": 16},
            {"id": "stepB", "entry": "experiments.E4b.stepb:task", "args": {"e4a_exp": "E4a"},
             "smoke_args": {"n_boot": 50}, "kind_slot": "cpu", "est_minutes": 5, "smoke_est_minutes": 2,
             "est_ram_gb": 6, "deps": ["exp:E4b", "scores"]},
        ],
        "jobs": {"group_size": 4, "est_seconds_per_item": 0.45, "est_vram_gb": 10, "est_ram_gb": 20,
                 "overhead_minutes": 2, "gpu_exclusive": True},
        "smoke": {"base": {"limit": 6}},
    }
    out = ROOT / "configs" / "experiments" / "E4b.yaml"
    out.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))
    print(out, len(cfg["runs"]), "runs")


if __name__ == "__main__":
    main()
