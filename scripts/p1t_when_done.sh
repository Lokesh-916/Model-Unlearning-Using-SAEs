#!/usr/bin/env bash
# Wait for the P1T queue jobs, then paste runs/P1T/summary/SUMMARY.md into
# docs/P1T_CYBER_TEST.md (between the P1T-SUMMARY markers), set the status line, commit (author only, no AI trailer)
# and push prep/later-runs. Never re-runs or re-queues anything. If a P1T job FAILED / is BLOCKED it writes that status.
#   nohup scripts/p1t_when_done.sh >> $DSG_RESULTS/p1t_watch.log 2>&1 &      (restart after a reboot)
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-600}
DOC=docs/P1T_CYBER_TEST.md
while true; do
  st=$($PY - <<'PYEOF'
import json, os, glob
S = os.environ["DSG_RESULTS"] + "/queue/state"
fs = [f for f in glob.glob(S + "/P1T-*.json") if "smoke" not in f]
st = [json.load(open(f)).get("status") for f in fs]
if any(s in ("FAILED", "BLOCKED") for s in st):
    print("BAD")
elif st and all(s == "DONE" for s in st):
    print("DONE")
else:
    print(f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
PYEOF
)
  echo "$(date -Iseconds) $st"
  case "$st" in
    BAD|DONE) break ;;
  esac
  sleep "$EVERY"
done
$PY - "$st" <<'PYEOF'
import os, re, sys
from pathlib import Path
st = sys.argv[1]
doc = Path("docs/P1T_CYBER_TEST.md")
s = doc.read_text()
summ = Path(os.environ["DSG_RESULTS"]) / "runs" / "P1T" / "summary" / "SUMMARY.md"
if st == "DONE" and summ.exists():
    body = summ.read_text()
    status = "**P1T status: DONE** (every P1T job finished; tables generated by `P1T-summary`; verdict at the end)."
else:
    body = "A P1T job FAILED or is BLOCKED: run `python -m dsgx.queue.doctor` (resume with item checkpoints). No result tables yet.\n"
    status = "**P1T status: STOPPED** (a P1T queue job failed or is blocked; see below)."
s = re.sub(r"<!-- P1T-SUMMARY -->.*<!-- /P1T-SUMMARY -->", lambda m: "<!-- P1T-SUMMARY -->\n" + body + "<!-- /P1T-SUMMARY -->", s, flags=re.S)
s = re.sub(r"^\*\*P1T status:.*$", status, s, count=1, flags=re.M)
doc.write_text(s)
PYEOF
git add "$DOC"
git commit -q -m "P1-T single TEST result of the P1 Cyber gate (lab PC): docs/P1T_CYBER_TEST.md from P1T-summary ($st)" \
  && git push -q origin prep/later-runs && echo "$(date -Iseconds) committed and pushed ($st)"
