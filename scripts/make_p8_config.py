"""Writes configs/experiments/P8.yaml: fixed generic jailbreak wrappers vs StreamGuard v2-R (DEV only, never TEST).
19 generation tasks (none + 6 wrappers x {alone, + pad400, + split3}), 150 DEV items each, arms A / B + base, then
the CPU summary. One GPU job at a time, item-level resume. Smoke = 2 DEV items, 8 tokens.

    python scripts/make_p8_config.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.P8.common import CONDITIONS, EXP, MAX_NEW, N_ITEMS, SUBSET_SEED, task_id  # noqa: E402

FROZEN = {"layer": 10, "s": 0.45, "mode": "start8",
          "direction_sha256": "f7d9a17e803a2ed4b526db1a4db70360e00229049b77893971b153ab1bb0fc0b"}


def est(cond):
    return 80 if cond.endswith("pad400") or cond.endswith("split3") else 70


def main():
    tasks, prev = [], []
    for c in CONDITIONS:
        tid = task_id(c)
        tasks.append({"id": tid, "entry": "experiments.P8.gen:task",
                      "args": {"items": "wmdp-bio-open", "split": "dev", "n_items": N_ITEMS, "subset_seed": SUBSET_SEED,
                               "max_new": MAX_NEW, "attack": c, "arms": ["A", "B"], "step1_exp": "E5b",
                               "direction": "base", "frozen": FROZEN},
                      "smoke_args": {"limit": 2, "max_new": 8},
                      "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": est(c), "smoke_est_minutes": 2,
                      "est_vram_gb": 10, "deps": prev[-1:]})
        prev.append(tid)
    tasks.append({"id": "summary", "entry": "experiments.P8.summary:task", "args": {}, "smoke_args": {"n_boot": 50},
                  "kind_slot": "cpu", "est_minutes": 5, "smoke_est_minutes": 2, "est_ram_gb": 4, "deps": prev})
    cfg = {"exp_id": EXP, "priority": "must", "wave": 9, "tasks": tasks}
    out = ROOT / "configs" / "experiments" / f"{EXP}.yaml"
    head = ("# generated by scripts/make_p8_config.py; do not edit by hand. P8 jailbreak wrappers vs StreamGuard v2-R\n"
            "# (DEV only, never TEST; frozen v2 gate cc6f375 + v2-R arm B; DEVIATIONS 2026-11-18 P8 row; lab PC only).\n")
    out.write_text(head + yaml.safe_dump(cfg, sort_keys=False, width=120))
    print(out, len(tasks), "tasks")


if __name__ == "__main__":
    main()
