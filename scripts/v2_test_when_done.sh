#!/usr/bin/env bash
# Wait for the StreamGuard v2 TEST (V2-devcheck + V2-test queue jobs), then write docs/V2_TEST_RESULT.md with
# python -m dsgx.analysis.v2_test, commit it (author only, no AI trailer) and push prep/later-runs.
# Never re-runs, re-thresholds or re-queues anything. If a V2 job FAILED / is BLOCKED, it writes a note and stops.
#   nohup scripts/v2_test_when_done.sh >> $DSG_RESULTS/../dsg_results/v2_test_watch.log 2>&1 &
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-600}
while true; do
  st=$($PY - <<'EOF'
import json, os, glob
S = os.environ["DSG_RESULTS"] + "/queue/state"
st = [json.load(open(f)).get("status") for f in glob.glob(S + "/V2-devcheck-*.json") + glob.glob(S + "/V2-test-*.json")
      if "smoke" not in f]
if any(s in ("FAILED", "BLOCKED") for s in st):
    print("BAD")
elif st and all(s == "DONE" for s in st):
    print("DONE")
else:
    print(f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
EOF
)
  echo "$(date -Iseconds) $st"
  case "$st" in
    BAD) echo "a V2 job FAILED or is BLOCKED: run python -m dsgx.queue.doctor; nothing written"; exit 1 ;;
    DONE) break ;;
  esac
  sleep "$EVERY"
done
CUDA_VISIBLE_DEVICES= $PY -m dsgx.analysis.v2_test --out docs/V2_TEST_RESULT.md > /dev/null || exit 1
git add docs/V2_TEST_RESULT.md
git commit -q -m "V2 TEST result (StreamGuard v2, frozen cc6f375, lab PC, 5 seeds): docs/V2_TEST_RESULT.md generated by dsgx.analysis.v2_test (claims V2 / V3 as evaluate_v2 decides)" \
  && git push -q origin prep/later-runs && echo "$(date -Iseconds) committed and pushed"
