#!/usr/bin/env bash
# Wait for the P8 queue jobs, then paste runs/P8/summary/SUMMARY.md into
# docs/P8_REFUSAL_JAILBREAKS.md (between the P8-SUMMARY markers), set the status line, commit (author only, no AI trailer)
# and push prep/later-runs. Never re-runs or re-queues anything. If a P8 job FAILED / is BLOCKED it writes that status.
#   nohup scripts/p8_when_done.sh >> $DSG_RESULTS/p8_watch.log 2>&1 &      (restart after a reboot)
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-600}
DOC=docs/P8_REFUSAL_JAILBREAKS.md
while true; do
  st=$($PY - <<'PYEOF'
import json, os, glob
S = os.environ["DSG_RESULTS"] + "/queue/state"
fs = [f for f in glob.glob(S + "/P8-*.json") if "smoke" not in f]
st = [json.load(open(f)).get("status") for f in fs]
if any(s in ("FAILED", "BLOCKED") for s in st):
    print("BAD")
elif st and all(s == "DONE" for s in st):
    print("DONE")
else:
    print(f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
PYEOF
)
  echo "$(date -Iseconds) $st"
  case "$st" in
    BAD|DONE) break ;;
  esac
  sleep "$EVERY"
done
$PY - "$st" <<'PYEOF'
import os, re, sys
from pathlib import Path
st = sys.argv[1]
doc = Path("docs/P8_REFUSAL_JAILBREAKS.md")
s = doc.read_text()
summ = Path(os.environ["DSG_RESULTS"]) / "runs" / "P8" / "summary" / "SUMMARY.md"
if st == "DONE" and summ.exists():
    body = summ.read_text()
    status = "**P8 status: DONE** (every P8 job finished; tables generated by `P8-summary`; verdict at the end)."
else:
    body = "A P8 job FAILED or is BLOCKED: run `python -m dsgx.queue.doctor` (resume with item checkpoints). No result tables yet.\n"
    status = "**P8 status: STOPPED** (a P8 queue job failed or is blocked; see below)."
s = re.sub(r"<!-- P8-SUMMARY -->.*<!-- /P8-SUMMARY -->", lambda m: "<!-- P8-SUMMARY -->\n" + body + "<!-- /P8-SUMMARY -->", s, flags=re.S)
s = re.sub(r"^\*\*P8 status:.*$", status, s, count=1, flags=re.M)
doc.write_text(s)
PYEOF
git add "$DOC"
git commit -q -m "P8 jailbreak wrappers vs StreamGuard v2-R (DEV only): docs/P8_REFUSAL_JAILBREAKS.md from P8-summary ($st)" -m "Co-authored-by: Chakrish28 <chakrish.konchada1234@gmail.com>" \
  && git push -q origin prep/later-runs && echo "$(date -Iseconds) committed and pushed ($st)"
