"""Generate configs/experiments/E2e.yaml (DEV only, never TEST).

Step A (CPU): task stepA, offline from the E2d runs.
Step B (GPU, --stage B): translate-forget (Hindi forget subset, NLLB) -> train (R6, R7) -> forced-on runs of R6, R7
and sgF (StreamGuard v1's clamp forced on every prompt: `gated`, same gate spec, threshold -1e30, for the exact
Step C clamp curve), each on clean dev (@forget + @utility + A3's five benign-biology subjects), pad400, split3,
Hindi; bs 1 -> stepB summary (CPU, Steps B + C).

    python scripts/make_e2e_config.py [--stage A|B]
"""
import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.E2d.common import ATTACKS, BENIGN_BIO  # noqa: E402

SGF = {"name": "gated", "gate": {"type": "cusum", "n_features": 20, "retain_pct": 95, "threshold": -1.0e30},
       "intervention": {"type": "clamp_all", "multiplier": 500}, "forced_on": True}
CLEAN = ["@forget", "@utility", *BENIGN_BIO]
HEADER = "# generated by scripts/make_e2e_config.py; do not edit by hand. DEV split only, never TEST.\n"


def runs():
    conds = [(r, {"name": "delta-response", "module": "experiments.E2d.response", "response": r,
                  "response_exp": "E2e", "forced_on": True}) for r in ("R6", "R7")] + [("sgF", SGF)]
    rs = []
    for cond, m in conds:
        for a, spec in ATTACKS.items():
            rs.append({"method": m, "attack": spec, "datasets": CLEAN if a == "clean" else ["@forget"],
                       "dataset_label": f"{cond}-{a}", "e2d": {"cond": cond, "attack": a}})
    return rs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="B", choices=["A", "B"])
    stage = ap.parse_args().stage
    base = {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0}
    step_a = {"id": "stepA", "entry": "experiments.E2e.analysis:task", "args": {"stage": "A"},
              "kind_slot": "cpu", "est_minutes": 5, "smoke_est_minutes": 2, "est_ram_gb": 6}
    cfg = {"exp_id": "E2e", "priority": "must", "wave": 9, "tasks": [step_a]}
    if stage == "B":
        cfg = {"exp_id": "E2e", "priority": "must", "wave": 9, "base": base, "runs": runs(), "tasks": [step_a]}
        cfg["jobs"] = {"group_size": 4, "est_seconds_per_item": 0.27, "est_vram_gb": 9, "est_ram_gb": 20,
                       "overhead_minutes": 2, "gpu_exclusive": True, "deps": ["train"]}
        cfg["tasks"] += [
            {"id": "translate-forget", "entry": "experiments.E2e.translate_forget:task", "args": {"batch_size": 16},
             "smoke_args": {"limit": 4}, "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": 45,
             "smoke_est_minutes": 3, "est_vram_gb": 4, "est_ram_gb": 10},
            {"id": "train", "entry": "experiments.E2e.train:task", "args": {}, "deps": ["translate-forget"],
             "smoke_args": {"max_num_batches": 2, "n_aug_docs": 20}, "kind_slot": "gpu", "gpu_exclusive": True,
             "est_minutes": 50, "smoke_est_minutes": 8, "est_vram_gb": 14, "est_ram_gb": 24},
            {"id": "stepB", "entry": "experiments.E2e.analysis:task", "args": {"stage": "B"}, "kind_slot": "cpu",
             "est_minutes": 10, "smoke_est_minutes": 2, "est_ram_gb": 8, "deps": ["exp:E2e", "stepA"]},
        ]
        cfg["smoke"] = {"base": {"limit": 6}, "runs": runs()}
    p = ROOT / "configs" / "experiments" / "E2e.yaml"
    p.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    print(f"wrote {p} ({len(cfg.get('runs', []))} runs, {len(cfg['tasks'])} tasks)")


if __name__ == "__main__":
    main()
