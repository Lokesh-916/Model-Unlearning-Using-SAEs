"""Generate configs/experiments/V2-devcheck.yaml (DEV replay of the frozen method) and V2-test.yaml (the single TEST
evaluation of StreamGuard v2). Lab PC only; batch size 1.

V2-devcheck: the frozen method on every DEV prompt E4a / E4b scored (WMDP-Bio dev clean / pad400 / split3 / Hindi,
benign biology, MMLU utility; E4b Step B bbio400 / bbio1600 / midpad400 / interleave2) + task `check` (fails, and so
blocks every V2-test job, if any gate decision differs from E4b's).

V2-test (5 seeds): StreamGuard v2 on WMDP-Bio clean + MMLU utility, benign biology (5 subjects, n 428), and the 18
attacks in experiments.V2.common.ATTACKS; DSG and StreamGuard v1 only where no lab-PC TEST log with identical items
exists (X1: 5 seeds; B1 / B2 / B3 / B7: seed 0); base-model controls for attack item sets not already logged.

    python scripts/make_v2_config.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.V2.common import (ATTACKS, BASE_ELSEWHERE, DEV_CONDS, DSG, DSG_S0_ELSEWHERE, EXP_DEV, EXP_TEST,  # noqa: E402
                                   HARDNEG, IN_X1, METHOD, SEEDS, SG1, SG1_S0_ELSEWHERE)

HEADER = "# generated by scripts/make_v2_config.py; do not edit by hand. StreamGuard v2 frozen (experiments/V2/common.py).\n"
JOBS = {"group_size": 6, "est_seconds_per_item": 0.33, "est_vram_gb": 10, "est_ram_gb": 20, "overhead_minutes": 3,
        "gpu_exclusive": True}


def devcheck_runs():
    out = [{"method": METHOD, "attack": {"name": "none"}, "datasets": ["@forget"] + HARDNEG + ["@utility"],
            "dataset_label": "sg2dev-clean"}]
    out += [{"method": METHOD, "attack": a, "datasets": ["@forget"], "dataset_label": f"sg2dev-{c}"}
            for c, a in DEV_CONDS.items() if c != "wmdp_clean"]
    return out


def test_runs():
    out = []
    for s in SEEDS:   # StreamGuard v2 first
        out.append({"method": METHOD, "attack": {"name": "none"}, "seed": s, "datasets": ["@forget", "@utility"],
                    "dataset_label": "sg2", "v2": {"cond": "sg2", "attack": "clean"}})
        out.append({"method": METHOD, "attack": {"name": "none"}, "seed": s, "datasets": HARDNEG,
                    "dataset_label": "sg2-hardneg", "v2": {"cond": "sg2", "attack": "benign-biology"}})
        out += [{"method": METHOD, "attack": a, "seed": s, "datasets": ["@forget"], "dataset_label": "sg2-forget",
                 "v2": {"cond": "sg2", "attack": k}} for k, a in ATTACKS.items()]
    for k, a in ATTACKS.items():
        if k in IN_X1:
            continue
        if k not in BASE_ELSEWHERE:
            out.append({"method": {"name": "base"}, "attack": a, "seed": 0, "datasets": ["@forget"],
                        "dataset_label": "base-forget", "v2": {"cond": "base", "attack": k}})
        for s in SEEDS:
            if not (s == 0 and k in DSG_S0_ELSEWHERE):
                out.append({"method": DSG, "attack": a, "seed": s, "datasets": ["@forget"],
                            "dataset_label": "dsg-forget", "v2": {"cond": "dsg", "attack": k}})
            if not (s == 0 and k in SG1_S0_ELSEWHERE):
                out.append({"method": SG1, "attack": a, "seed": s, "datasets": ["@forget"],
                            "dataset_label": "combined-forget", "v2": {"cond": "sg1", "attack": k}})
    return out


def main():
    dev = {"exp_id": EXP_DEV, "priority": "must", "wave": 9,
           "base": {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0},
           "runs": devcheck_runs(),
           "tasks": [{"id": "check", "entry": "experiments.V2.devcheck:task", "args": {}, "smoke_args": {"smoke": True},
                      "kind_slot": "cpu", "est_minutes": 3, "smoke_est_minutes": 1, "est_ram_gb": 4,
                      "deps": [f"exp:{EXP_DEV}"]}],
           "jobs": JOBS, "smoke": {"base": {"limit": 3}}}
    test = {"exp_id": EXP_TEST, "priority": "must", "wave": 9,
            "base": {"case": "bio", "split": "test", "purpose": "report", "view": "both", "batch_size": 1},
            "runs": test_runs(), "jobs": JOBS}
    for cfg, name in ((dev, "V2-devcheck.yaml"), (test, "V2-test.yaml")):
        p = ROOT / "configs" / "experiments" / name
        p.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))
        print(p, len(cfg["runs"]), "runs")


if __name__ == "__main__":
    main()
