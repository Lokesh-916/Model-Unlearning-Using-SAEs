#!/usr/bin/env bash
# Wait for the V2R (StreamGuard v2-R single TEST evaluation) queue jobs, then paste runs/V2R/summary/SUMMARY.md into
# docs/V2R_TEST_RESULT.md (between the V2R-SUMMARY markers), set the status line, commit (author only, no AI trailer)
# and push prep/later-runs. Never re-runs or re-queues anything. If a V2R job FAILED / is BLOCKED it writes that status.
#   nohup scripts/v2r_when_done.sh >> $DSG_RESULTS/v2r_watch.log 2>&1 &      (restart after a reboot)
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-600}
DOC=docs/V2R_TEST_RESULT.md
while true; do
  st=$($PY - <<'PYEOF'
import json, os, glob
S = os.environ["DSG_RESULTS"] + "/queue/state"
fs = [f for f in glob.glob(S + "/V2R-*.json") if "smoke" not in f]
st = [json.load(open(f)).get("status") for f in fs]
if any(s in ("FAILED", "BLOCKED") for s in st):
    print("BAD")
elif st and all(s == "DONE" for s in st):
    print("DONE")
else:
    print(f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
PYEOF
)
  echo "$(date -Iseconds) $st"
  case "$st" in
    BAD|DONE) break ;;
  esac
  sleep "$EVERY"
done
$PY - "$st" <<'PYEOF'
import os, re, sys
from pathlib import Path
st = sys.argv[1]
doc = Path("docs/V2R_TEST_RESULT.md")
s = doc.read_text()
summ = Path(os.environ["DSG_RESULTS"]) / "runs" / "V2R" / "summary" / "SUMMARY.md"
if st == "DONE" and summ.exists():
    body = summ.read_text()
    status = "**V2R status: DONE** (all 5 V2R queue jobs finished; tables generated by `V2R-summary`; verdict at the end)."
else:
    body = "A V2R job FAILED or is BLOCKED: run `python -m dsgx.queue.doctor` (resume with item checkpoints). No result tables yet.\n"
    status = "**V2R status: STOPPED** (a V2R queue job failed or is blocked; see below)."
s = re.sub(r"<!-- V2R-SUMMARY -->.*<!-- /V2R-SUMMARY -->", lambda m: "<!-- V2R-SUMMARY -->\n" + body + "<!-- /V2R-SUMMARY -->", s, flags=re.S)
s = re.sub(r"^\*\*V2R status:.*$", status, s, count=1, flags=re.M)
doc.write_text(s)
PYEOF
git add "$DOC"
git commit -q -m "StreamGuard v2-R single TEST result (lab PC, weaker setting): docs/V2R_TEST_RESULT.md from V2R-summary ($st)" \
  && git push -q origin prep/later-runs && echo "$(date -Iseconds) committed and pushed ($st)"
