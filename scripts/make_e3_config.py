"""Writes configs/experiments/E3.yaml (55 DEV runs + rank + summary tasks). Re-run after editing experiments/E3/common.py."""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from experiments.E3.common import BENIGN_BIO, N_RANDOM, SAES, TOPK  # noqa: E402

DSG_SAE = "layer_3/width_16k/average_l0_142"


def runs(exp, tags):
    out = []
    for tag, sid in SAES:
        if tag not in tags:
            continue
        for kind in [f"causal{k}" for k in TOPK] + [f"rand{N_RANDOM}"]:
            out.append({"model": {"sae_id": sid}, "dataset_label": f"{tag}-{kind}",
                        "method": {"name": "zero-ablate", "module": "experiments.E3.ablate", "features_exp": exp,
                                   "features_name": f"{tag}__{kind}"}})
    out.append({"model": {"sae_id": DSG_SAE}, "dataset_label": "L03dsg-dsg20-zero",
                "method": {"name": "zero-ablate", "module": "experiments.E3.ablate", "dsg_features": True,
                           "n_features": 20, "retain_pct": 95}})
    out.append({"model": {"sae_id": DSG_SAE}, "dataset_label": "L03dsg-dsg-clamp-forced",
                "method": {"name": "dsg-faithful", "n_features": 20, "retain_pct": 95, "multiplier": 500, "tau": -1.0}})
    out.append({"model": {"sae_id": DSG_SAE}, "dataset_label": "base", "method": {"name": "base"}})
    return out


all_tags = [t for t, _ in SAES]
smoke_tags = ["L03", "L03dsg"]
cfg = {
    "exp_id": "E3",
    "priority": "must",
    "wave": 9,
    "base": {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 8, "seed": 0,
             "attack": {"name": "none"}, "datasets": ["@forget", "@utility", *BENIGN_BIO]},
    "runs": runs("E3", all_tags),
    "jobs": {"group_size": 7, "est_seconds_per_item": 0.08, "est_vram_gb": 11, "est_ram_gb": 20,
             "overhead_minutes": 2, "gpu_exclusive": True, "deps": ["rank"]},
    "tasks": [
        {"id": "rank", "entry": "experiments.E3.rank:task", "args": {"n_retain": 640}, "kind_slot": "gpu",
         "gpu_exclusive": True, "est_minutes": 75, "est_vram_gb": 12, "est_ram_gb": 20,
         "smoke_args": {"saes": smoke_tags, "n_fit": 6, "n_retain": 6}, "smoke_est_minutes": 4},
        {"id": "summary", "entry": "experiments.E3.summary:task", "kind_slot": "cpu", "est_minutes": 5,
         "smoke_est_minutes": 1, "est_ram_gb": 4, "deps": ["exp:E3"]},
    ],
    "smoke": {"base": {"limit": 6}, "runs": runs("E3-smoke", smoke_tags)},
}
p = Path(__file__).resolve().parents[1] / "configs/experiments/E3.yaml"
hdr = ("# E3 'detect here, erase there' (generated by scripts/make_e3_config.py). DEV split only, never TEST.\n"
       "# Attribution-patching ranking per Gemma Scope 16k canonical SAE (layers 3-14) + DSG's L3 SAE, then forced-on\n"
       "# ZERO-ablation (SAE error added back) of the top 10/20/50 causal features, 50 random alive features, DSG's 20\n"
       "# features, and DSG's -500 clamp forced-on (tau -1). Exploratory; not a claim input (dev only).\n")
p.write_text(hdr + yaml.safe_dump(cfg, sort_keys=False, width=120))
print(p, len(cfg["runs"]), "runs")
