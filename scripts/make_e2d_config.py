"""Generate configs/experiments/E2d.yaml and E2d-curve.yaml (DEV only, never TEST).

E2d: base, DSG (A1-dev selection), StreamGuard v1 (X1 `combined`: CUSUM gate + clamp_all 500) and the five
forced-on responses R1-R5, each on clean dev (@forget + @utility + A3's five benign-biology subjects) and on
WMDP-Bio dev under B1 pad400 (before, wikitext), B2 three-turn split and B3 Hindi. Batch size 1 everywhere.
E2d-curve (Step 4, lowest priority, enqueued behind E2d-summary): DSG's 20 features clamped forced-on (tau -1)
at -5 / -20 / -50 / -100 / -500 on clean dev.

    python scripts/make_e2d_config.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.E2d.common import ATTACKS, BENIGN_BIO, CLAMPS, LADDER  # noqa: E402

DSG = {"name": "dsg-faithful", "select": {"exp_id": "A1-dev", "keys": ["n_features", "retain_pct", "multiplier"],
                                          "max_utility_drop": 0.01}}
SG1 = {"name": "gated", "gate": {"type": "cusum", "n_features": 20, "retain_pct": 95},
       "calib": {"fpr": 0.05, "n_max": 1000, "source": "mmlu-dev"},
       "intervention": {"type": "clamp_all", "multiplier": 500}}
CLEAN = ["@forget", "@utility", *BENIGN_BIO]
HEADER = "# generated by scripts/make_e2d_config.py; do not edit by hand. DEV split only, never TEST.\n"


def conditions(response_exp):
    out = [("base", {"name": "base"}), ("dsg", DSG), ("sg1", SG1)]
    out += [(r, {"name": "delta-response", "module": "experiments.E2d.response", "response": r,
                 "response_exp": response_exp, "forced_on": True}) for r in LADDER]
    return out


def runs(response_exp):
    rs = []
    for cond, m in conditions(response_exp):
        for a, spec in ATTACKS.items():
            rs.append({"method": m, "attack": spec, "datasets": CLEAN if a == "clean" else ["@forget"],
                       "dataset_label": f"{cond}-{a}", "e2d": {"cond": cond, "attack": a}})
    return rs


def main():
    base = {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0}
    e2d = {
        "exp_id": "E2d", "priority": "must", "wave": 9, "base": base, "runs": runs("E2d"),
        "jobs": {"group_size": 4, "est_seconds_per_item": 0.27, "est_vram_gb": 9, "est_ram_gb": 20,
                 "overhead_minutes": 2, "gpu_exclusive": True, "deps": ["translate", "train"]},
        "tasks": [
            {"id": "translate", "entry": "experiments.E2d.translate:task",
             "args": {"dataset": "wmdp-bio", "lang": "hi", "split": "dev", "batch_size": 16},
             "smoke_args": {"limit": 6}, "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": 20,
             "smoke_est_minutes": 3, "est_vram_gb": 4, "est_ram_gb": 8},
            {"id": "train", "entry": "experiments.E2d.train:task", "args": {}, "deps": ["translate"],
             "smoke_args": {"max_num_batches": 2}, "kind_slot": "gpu", "gpu_exclusive": True,
             "est_minutes": 110, "smoke_est_minutes": 6, "est_vram_gb": 12, "est_ram_gb": 24},
            {"id": "summary", "entry": "experiments.E2d.summary:task", "kind_slot": "cpu", "est_minutes": 5,
             "smoke_est_minutes": 1, "est_ram_gb": 6, "deps": ["exp:E2d"]},
        ],
        "smoke": {"base": {"limit": 6}, "runs": runs("E2d-smoke")},
    }
    curve_runs = [{"method": {"name": "dsg-faithful", "n_features": 20, "retain_pct": 95, "multiplier": float(c),
                              "tau": -1.0, "forced_on": True},
                   "attack": {"name": "none"}, "datasets": CLEAN, "dataset_label": f"clamp{c}-forced"} for c in CLAMPS]
    curve = {
        "exp_id": "E2d-curve", "priority": "could", "wave": 9, "base": base, "runs": curve_runs,
        "jobs": {"group_size": 1, "est_seconds_per_item": 0.27, "est_vram_gb": 9, "est_ram_gb": 20,
                 "overhead_minutes": 2, "gpu_exclusive": True},
        "tasks": [{"id": "summary", "entry": "experiments.E2d.summary:task", "args": {"with_curve": True},
                   "kind_slot": "cpu", "est_minutes": 5, "smoke_est_minutes": 1, "est_ram_gb": 6,
                   "deps": ["exp:E2d-curve"]}],
        "smoke": {"base": {"limit": 6}, "runs": curve_runs[:1]},
    }
    out = ROOT / "configs" / "experiments"
    out.mkdir(parents=True, exist_ok=True)
    for name, cfg in (("E2d", e2d), ("E2d-curve", curve)):
        (out / f"{name}.yaml").write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))
        print(f"wrote {out / name}.yaml ({len(cfg['runs'])} runs)")


if __name__ == "__main__":
    main()
