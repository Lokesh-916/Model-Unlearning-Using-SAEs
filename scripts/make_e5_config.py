"""Write configs/experiments/E5.yaml (E5 gate-triggered self-refusal; DEV only, never TEST; lab PC).

Tasks run one GPU job at a time in this order: refusal (Step 1) -> sae (Step 2) -> gen-wmdp -> gen-benign ->
gen-wmdp-pad400 -> gen-wmdp-split3 -> gen-tofu-forget -> gen-tofu-retain -> MCQ runs (arms B-E) -> summary (CPU).
The MCQ method config = the frozen StreamGuard v2 METHOD + arm (experiments.E5.method)."""
import copy
from pathlib import Path

import yaml

from experiments.V2.common import METHOD

ROOT = Path(__file__).resolve().parents[1]
BENIGN = "mmlu-open:college_biology,high_school_biology,anatomy,virology,medical_genetics"
SMOKE_GEN = {"limit": 3, "max_new": 16}


def arm_method(arm, e5_exp):
    m = copy.deepcopy(METHOD)
    m.update({"name": "sg2-arm", "module": "experiments.E5.method", "arm": arm, "e5_exp": e5_exp})
    return m


def gen(tid, items, deps, est, **kw):
    args = {"items": items, "split": "dev", "n_items": 150, "subset_seed": 0, "max_new": 96, "attack": "none", **kw}
    return {"id": tid, "entry": "experiments.E5.gen:task", "args": args, "smoke_args": dict(SMOKE_GEN),
            "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": est, "est_vram_gb": 10, "deps": deps}


def main():
    tofu = {"model": {"weights": "ckpt:E2f/tofu_full"}, "direction": "tofu"}
    tasks = [
        {"id": "refusal", "entry": "experiments.E5.refusal:task", "args": {"max_new": 96},
         "smoke_args": {"limit": 3, "max_new": 16, "smoke_force": {"layer": 12, "s": 1.0}},
         "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": 30, "est_vram_gb": 12},
        {"id": "sae", "entry": "experiments.E5.sae:task", "args": {"max_new": 96}, "smoke_args": {"limit": 3, "max_new": 16},
         "kind_slot": "gpu", "gpu_exclusive": True, "est_minutes": 15, "est_vram_gb": 10, "deps": ["refusal"]},
        gen("gen-wmdp", "wmdp-bio-open", ["sae"], 45, curve=True),
        gen("gen-benign", BENIGN, ["gen-wmdp"], 35, curve=True),
        gen("gen-wmdp-pad400", "wmdp-bio-open", ["gen-benign"], 45, attack="pad400"),
        gen("gen-wmdp-split3", "wmdp-bio-open", ["gen-wmdp-pad400"], 40, attack="split3"),
        gen("gen-tofu-forget", "tofu-forget10", ["gen-wmdp-split3"], 30, **tofu),
        gen("gen-tofu-retain", "tofu-retain_perturbed", ["gen-tofu-forget"], 30, **tofu),
        {"id": "summary", "entry": "experiments.E5.summary:task", "args": {}, "smoke_args": {"n_boot": 50},
         "kind_slot": "cpu", "est_minutes": 5, "est_ram_gb": 4, "smoke_est_minutes": 2,
         "deps": ["gen-wmdp", "gen-benign", "gen-wmdp-pad400", "gen-wmdp-split3", "gen-tofu-forget", "gen-tofu-retain",
                  "exp:E5"]},
    ]
    runs = lambda e: [{"method": arm_method(a, e), "dataset_label": f"e5-arm{a}"} for a in "BCDE"]  # noqa: E731
    cfg = {"exp_id": "E5", "priority": "must", "wave": 9,
           "base": {"case": "bio", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0,
                    "attack": {"name": "none"}, "datasets": ["@forget", "@utility"]},
           "runs": runs("E5"), "tasks": tasks,
           "jobs": {"group_size": 1, "est_seconds_per_item": 0.35, "est_vram_gb": 10, "est_ram_gb": 20,
                    "overhead_minutes": 3, "gpu_exclusive": True, "deps": ["gen-tofu-retain"]},
           "smoke": {"base": {"limit": 3}, "runs": runs("E5-smoke")}}
    out = ROOT / "configs" / "experiments" / "E5.yaml"
    head = ("# generated by scripts/make_e5_config.py; do not edit by hand. E5 gate-triggered self-refusal: POST-v2\n"
            "# EXTENSION, EXPLORATORY, DEV only (never TEST), lab PC; frozen StreamGuard v2 unchanged (DEVIATIONS 2026-11-14).\n"
            "# TOFU sets have no dev split in this project and are used whole (150-item seeded subset), as in E2f.\n")
    out.write_text(head + yaml.safe_dump(cfg, sort_keys=False, width=120))
    print(out)


if __name__ == "__main__":
    main()
