"""Writes configs/experiments/P1T-devcheck.yaml (DEV replay of the frozen P1 Cyber gate; blocks TEST on any decision
change) and configs/experiments/P1T.yaml (its single TEST evaluation: 5 seeds, bs 1, lab PC).

P1T: frozen gate (experiments.P1T.common.METHOD) seeds 0-4, DSG paper recipe and DSG chat-retain seeds 0-4 (calib seed
= run seed), base seed 0 (seed-invariant); each on WMDP-Cyber clean (+ benign computing + full-MMLU utility, Cyber set),
pad400, split3. Every TEST job depends on P1T-devcheck-check.

    python scripts/make_p1t_config.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.P1T.common import ATTACKS, BENIGN_CS, COMPARATORS, EXP_DEV, EXP_TEST, METHOD, SEEDS  # noqa: E402

HDR = ("# generated by scripts/make_p1t_config.py; do not edit by hand. P1-T: single TEST evaluation of the P1 Cyber gate\n"
       "# (L08 op5 -> DSG Cyber clamp; frozen in experiments/P1T/common.py; DEVIATIONS 2026-11-18 P1-T row; lab PC only).\n")
JOBS = {"group_size": 3, "gpu_exclusive": True, "est_seconds_per_item": 0.235, "est_vram_gb": 10, "est_ram_gb": 20,
        "overhead_minutes": 2}


def ds_for(k):
    return ["@forget"] + (BENIGN_CS + ["@utility"] if k == "clean" else [])


def dev_runs():
    return [{"method": METHOD, "attack": dict(a), "datasets": ["@forget"] + (BENIGN_CS if k == "clean" else []),
             "dataset_label": f"p1tdev-{k}"} for k, a in ATTACKS.items()]


def test_runs():
    out = []
    for s in SEEDS:                                    # the frozen gate first
        out += [{"method": METHOD, "attack": dict(a), "seed": s, "datasets": ds_for(k),
                 "dataset_label": f"p1t-gate-{k}"} for k, a in ATTACKS.items()]
    out += [{"method": {"name": "base"}, "attack": dict(a), "seed": 0, "datasets": ds_for(k),
             "dataset_label": f"p1t-base-{k}"} for k, a in ATTACKS.items()]
    for c, m in COMPARATORS.items():
        for s in SEEDS:
            out += [{"method": dict(m), "attack": dict(a), "seed": s, "datasets": ds_for(k),
                     "dataset_label": f"p1t-{c}-{k}"} for k, a in ATTACKS.items()]
    return out


def main():
    dev = {"exp_id": EXP_DEV, "priority": "must", "wave": 9,
           "base": {"case": "cyber", "split": "dev", "purpose": "explore", "view": "raw", "batch_size": 1, "seed": 0},
           "runs": dev_runs(), "smoke": {"base": {"limit": 4}},
           "jobs": {**JOBS, "group_size": 3},
           "tasks": [{"id": "check", "entry": "experiments.P1T.devcheck:task", "args": {}, "smoke_args": {"smoke": True},
                      "kind_slot": "cpu", "est_minutes": 2, "smoke_est_minutes": 1, "est_ram_gb": 4,
                      "deps": [f"exp:{EXP_DEV}"]}]}
    test = {"exp_id": EXP_TEST, "priority": "must", "wave": 9,
            "base": {"case": "cyber", "split": "test", "purpose": "report", "view": "raw", "batch_size": 1},
            "runs": test_runs(), "jobs": {**JOBS, "deps": [f"{EXP_DEV}-check"]},
            "tasks": [{"id": "summary", "entry": "experiments.P1T.summary:task", "args": {}, "kind_slot": "cpu",
                       "est_minutes": 8, "est_ram_gb": 6, "deps": [f"exp:{EXP_TEST}"]}]}
    for cfg, name in ((dev, f"{EXP_DEV}.yaml"), (test, f"{EXP_TEST}.yaml")):
        p = ROOT / "configs" / "experiments" / name
        p.write_text(HDR + yaml.safe_dump(cfg, sort_keys=False))
        print(p, len(cfg["runs"]), "runs")


if __name__ == "__main__":
    main()
