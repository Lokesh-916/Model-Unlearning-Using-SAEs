#!/usr/bin/env bash
# Wait for E5 (gate-triggered self-refusal, DEV only) queue jobs, then paste runs/E5/summary/SUMMARY.md into
# docs/E5_SELF_REFUSAL.md (between the E5-SUMMARY markers), set the status line, commit (author only, no AI
# trailer) and push prep/later-runs. Never re-runs or re-queues anything. If an E5 job FAILED / is BLOCKED it writes
# that status into the doc, commits, and stops.
#   nohup scripts/e5_when_done.sh >> $DSG_RESULTS/e5_watch.log 2>&1 &      (restart after a reboot)
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
source scripts/env.sh
PY=~/miniconda3/envs/mechunlearn2/bin/python
EVERY=${EVERY:-600}
DOC=docs/E5_SELF_REFUSAL.md
while true; do
  st=$($PY - <<'EOF'
import json, os, glob
S = os.environ["DSG_RESULTS"] + "/queue/state"
fs = [f for f in glob.glob(S + "/E5-*.json") if "smoke" not in f]
st = [json.load(open(f)).get("status") for f in fs]
if any(s in ("FAILED", "BLOCKED") for s in st):
    print("BAD")
elif st and all(s == "DONE" for s in st):
    print("DONE")
else:
    print(f"WAIT {sum(s == 'DONE' for s in st)}/{len(st)}")
EOF
)
  echo "$(date -Iseconds) $st"
  case "$st" in
    BAD|DONE) break ;;
  esac
  sleep "$EVERY"
done
$PY - "$st" <<'EOF'
import os, re, sys
from pathlib import Path
st = sys.argv[1]
doc = Path("docs/E5_SELF_REFUSAL.md")
s = doc.read_text()
summ = Path(os.environ["DSG_RESULTS"]) / "runs" / "E5" / "summary" / "SUMMARY.md"
if st == "DONE" and summ.exists():
    body = summ.read_text()
    status = "**Status: DONE** (all E5 queue jobs finished; tables below generated by `E5-summary`)."
else:
    body = "An E5 job FAILED or is BLOCKED: run `python -m dsgx.queue.doctor`. No result tables were written.\n"
    status = "**Status: STOPPED** (an E5 queue job failed or is blocked; see below)."
s = re.sub(r"<!-- E5-SUMMARY -->.*<!-- /E5-SUMMARY -->", lambda m: "<!-- E5-SUMMARY -->\n" + body + "<!-- /E5-SUMMARY -->", s, flags=re.S)
s = re.sub(r"^\*\*Status:.*$", status, s, count=1, flags=re.M)
doc.write_text(s)
EOF
git add "$DOC"
git commit -q -m "E5 self-refusal result (DEV only, exploratory, lab PC): docs/E5_SELF_REFUSAL.md tables from E5-summary ($st)" \
  && git push -q origin prep/later-runs && echo "$(date -Iseconds) committed and pushed ($st)"
